package com.ekkus.offlineytplayer.coregateway

import android.os.Looper
import com.ekkus.offlineytplayer.SupportedUrlPolicy
import java.io.Closeable
import java.lang.reflect.Method

data class CoreSourceQualityChoice(
    val label: String,
    val estimatedBytes: Long?,
    val choiceId: String = label,
    val separateAudio: Boolean = false,
)

data class CoreSourceSubtitleChoice(
    val trackId: String,
    val language: String,
    val label: String?,
    val format: String,
    val autoGenerated: Boolean,
)

data class CoreSourceAudioChoice(
    val formatId: String,
    val label: String,
    val container: String,
    val bitrateBps: Long?,
)

data class CoreSourceAnalysis(
    val sourceUrl: String,
    val title: String,
    val durationMs: Long?,
    val thumbnailUrl: String?,
    val qualityLabel: String,
    val estimatedBytes: Long?,
    val qualityOptions: List<CoreSourceQualityChoice> = emptyList(),
    val subtitleOptions: List<CoreSourceSubtitleChoice> = emptyList(),
    val audioOptions: List<CoreSourceAudioChoice> = emptyList(),
    val containerOptions: List<String> = emptyList(),
    val sourceProvider: String? = null,
    val sourceMediaId: String? = null,
)

interface AppSourceAnalysisGateway : Closeable {
    fun analyze(sourceUrl: String): CoreGatewayResult<CoreSourceAnalysis>
}

/** Production-only source analysis boundary backed by FfiYouTubeSourceService. */
class GeneratedUniffiSourceAnalysisGateway private constructor(
    private val sourceService: Any,
) : AppSourceAnalysisGateway {
    override fun analyze(sourceUrl: String): CoreGatewayResult<CoreSourceAnalysis> {
        check(Looper.myLooper() != Looper.getMainLooper()) {
            "Source analysis is blocking and must run off the Android main thread"
        }
        val normalized = SupportedUrlPolicy.normalizeSupportedUrl(sourceUrl)
            ?: return CoreGatewayResult(
                null,
                CoreGatewayError(
                    "UNSUPPORTED_SOURCE",
                    "Enter a supported YouTube video URL",
                    false,
                ),
            )
        val token = newGeneratedObject("com.ekkus.offlineytplayer.core.FfiCancellationToken", "new")
        val resolved = callTwoArg(sourceService, "resolve", normalized, token)
        readSourceError(resolved)?.let { return CoreGatewayResult(null, it) }
        val media = readSourceRequired(resolved, "media")
        val choicesResult = callTwoArg(sourceService, "listChoices", normalized, token)
        readSourceError(choicesResult)?.let { return CoreGatewayResult(null, it) }
        val choices = readSourceList(choicesResult, "choices")
        val qualityOptions = disambiguateSourceQualityLabels(choices.map { choice ->
            CoreSourceQualityChoice(
                label = SourceMetadataPolicy.qualityLabel(readSourceString(choice, "label")),
                estimatedBytes = readSourceNullable(choice, "estimatedBytes", "estimated_bytes")?.let(::generatedNumericAsLong),
                choiceId = readSourceString(choice, "choiceId", "choice_id"),
                separateAudio = readSourceRequired(choice, "separateAudio", "separate_audio") as Boolean,
            )
        })
        val sourceIdentity = readSourceRequired(media, "source")
        val subtitleOptions = disambiguateSourceSubtitleLabels(readSourceList(media, "subtitleOptions", "subtitle_options").map { option ->
            CoreSourceSubtitleChoice(
                trackId = readSourceString(option, "trackId", "track_id"),
                language = readSourceString(option, "language"),
                label = readSourceNullable(option, "label") as String?,
                format = readSourceString(option, "format"),
                autoGenerated = readSourceRequired(option, "autoGenerated", "auto_generated") as Boolean,
            )
        })
        val audioOptions = disambiguateSourceAudioLabels(readSourceList(media, "audioOptions", "audio_options").map { option ->
            CoreSourceAudioChoice(
                formatId = readSourceString(option, "formatId", "format_id"),
                label = readSourceString(option, "label"),
                container = readSourceString(option, "container"),
                bitrateBps = readSourceNullable(option, "bitrateBps", "bitrate_bps")?.let(::generatedNumericAsLong),
            )
        })
        val containerOptions = readRequiredSourceStringList(media, "containerOptions", "container_options")
        val preferred = qualityOptions.firstOrNull()
        return CoreGatewayResult(
            CoreSourceAnalysis(
                sourceUrl = canonicalSourceUrl(media) ?: normalized,
                title = SourceMetadataPolicy.title(readSourceString(media, "title")),
                durationMs = readSourceNullable(media, "durationMs", "duration_ms")?.let(::generatedNumericAsLong),
                thumbnailUrl = readSourceNullable(media, "thumbnailUrl", "thumbnail_url") as String?,
                qualityLabel = preferred?.label ?: "No compatible format",
                estimatedBytes = preferred?.estimatedBytes,
                qualityOptions = qualityOptions,
                subtitleOptions = subtitleOptions,
                audioOptions = audioOptions,
                containerOptions = containerOptions,
                sourceProvider = readSourceString(sourceIdentity, "provider"),
                sourceMediaId = readSourceString(sourceIdentity, "mediaId", "media_id"),
            ),
            null,
        )
    }

    override fun close() = Unit

    companion object {
        fun open(): GeneratedUniffiSourceAnalysisGateway {
            // MainActivity must prove that the shipped ABI and generated bindings can
            // actually execute a call, not just load a Kotlin class by reflection.
            System.loadLibrary("offline_yt_core")
            val service = newGeneratedObject("com.ekkus.offlineytplayer.core.FfiYouTubeSourceService", "new")
            val token = newGeneratedObject("com.ekkus.offlineytplayer.core.FfiCancellationToken", "new")
            // Deliberately unsupported host: Rust rejects it before any network
            // request, keeping production bootstrap and emulator smoke deterministic.
            val probe = callTwoArg(
                service, "resolve", "https://unsupported.invalid/watch?v=dQw4w9WgXcQ", token,
            )
            check(readSourceError(probe)?.kind?.contains("UNSUPPORTED", ignoreCase = true) == true) {
                "Packaged YouTube resolver failed its native interop preflight"
            }
            return GeneratedUniffiSourceAnalysisGateway(service)
        }
    }
}

/** Keep every distinct provider choice selectable even when human labels collide. */
internal fun disambiguateSourceQualityLabels(
    choices: List<CoreSourceQualityChoice>,
): List<CoreSourceQualityChoice> {
    // Reserve original labels first, so a generated suffix never steals the
    // genuine label of a later provider format (e.g. \"720p (2)\").
    val reserved = choices.map { it.label }.toSet()
    val used = mutableSetOf<String>()
    return choices.map { choice ->
        val label = choice.label
        if (used.add(label)) {
            choice
        } else {
            var suffix = 2
            var disambiguated: String
            do {
                disambiguated = "$label ($suffix)"
                suffix++
            } while (disambiguated in reserved || disambiguated in used)
            used.add(disambiguated)
            choice.copy(label = disambiguated)
        }
    }
}

/** Keep generated audio choice labels unique before AddScreen keys them by label. */
internal fun disambiguateSourceAudioLabels(
    choices: List<CoreSourceAudioChoice>,
): List<CoreSourceAudioChoice> {
    val originalLabels = choices.map { it.label.takeIf(String::isNotBlank) ?: "Audio format" }
    val reserved = originalLabels.toSet()
    val used = mutableSetOf<String>()
    return choices.mapIndexed { index, choice ->
        val label = originalLabels[index]
        if (used.add(label)) choice.copy(label = label) else {
            var suffix = 2
            var candidate: String
            do {
                candidate = "$label ($suffix)"
                suffix++
            } while (candidate in reserved || candidate in used)
            used.add(candidate)
            choice.copy(label = candidate)
        }
    }
}

/** Match the key built by AddScreen's sourceSubtitleLabel, including (auto). */
private fun subtitlePresentationKey(choice: CoreSourceSubtitleChoice): String {
    val base = choice.label?.takeIf(String::isNotBlank) ?: choice.language
    return if (choice.autoGenerated) "$base (auto)" else base
}

/** Keep track IDs selectable even when generated and manual labels collide. */
internal fun disambiguateSourceSubtitleLabels(
    choices: List<CoreSourceSubtitleChoice>,
): List<CoreSourceSubtitleChoice> {
    val reserved = choices.map(::subtitlePresentationKey).toSet()
    val used = mutableSetOf<String>()
    return choices.map { choice ->
        val key = subtitlePresentationKey(choice)
        if (used.add(key)) choice else {
            val base = choice.label?.takeIf(String::isNotBlank) ?: choice.language
            var suffix = 2
            var candidateBase: String
            var candidateKey: String
            do {
                candidateBase = "$base ($suffix)"
                candidateKey = if (choice.autoGenerated) "$candidateBase (auto)" else candidateBase
                suffix++
            } while (candidateKey in reserved || candidateKey in used)
            used.add(candidateKey)
            choice.copy(label = candidateBase)
        }
    }
}

private fun canonicalSourceUrl(media: Any): String? {
    val source = readSourceNullable(media, "source") ?: return null
    return readSourceNullable(source, "canonicalUrl", "canonical_url") as String?
}

private fun newGeneratedObject(className: String, factoryName: String): Any {
    val type = Class.forName(className)
    type.methods.firstOrNull { it.name == factoryName && it.parameterTypes.isEmpty() }
        ?.let { return it.invoke(null) ?: error("$className.$factoryName returned null") }
    val companion = type.getDeclaredField("Companion").get(null)
    val factory: Method = companion.javaClass.methods.firstOrNull {
        it.name == factoryName && it.parameterTypes.isEmpty()
    } ?: error("$className has no $factoryName() factory")
    return factory.invoke(companion) ?: error("$className.$factoryName returned null")
}

private fun callTwoArg(target: Any, methodName: String, first: Any, second: Any): Any {
    val method = target.javaClass.methods.firstOrNull {
        it.name == methodName && it.parameterTypes.size == 2
    } ?: error("Generated source service does not expose $methodName")
    return method.invoke(target, first, second) ?: error("Generated source service returned null for $methodName")
}

private fun readSourceError(result: Any): CoreGatewayError? {
    val error = readSourceNullable(result, "error") ?: return null
    return CoreGatewayError(
        kind = readSourceRequired(error, "kind").toString(),
        message = readSourceString(error, "message"),
        retryable = readSourceRequired(error, "retryable") as Boolean,
    )
}

private fun readSourceRequired(target: Any, vararg names: String): Any =
    readSourceNullable(target, *names) ?: error("Missing generated property ${names.joinToString("/")}")

private fun readSourceNullable(target: Any, vararg names: String): Any? {
    for (name in names) {
        target.javaClass.methods.firstOrNull {
            it.name == name || it.name == "get${name.replaceFirstChar(Char::uppercase)}"
        }?.takeIf { it.parameterTypes.isEmpty() }?.let { return it.invoke(target) }
        target.javaClass.declaredFields.firstOrNull { it.name == name }?.let { field ->
            field.isAccessible = true
            return field.get(target)
        }
    }
    return null
}

@Suppress("UNCHECKED_CAST")
private fun readSourceList(target: Any, vararg names: String): List<Any> =
    readSourceRequired(target, *names) as List<Any>

internal fun readRequiredSourceStringList(target: Any, vararg names: String): List<String> {
    val value = readSourceRequired(target, *names)
    val list = value as? List<*>
        ?: error("Generated property ${names.joinToString("/")} is not a List")
    return list.mapIndexed { index, item ->
        item as? String
            ?: error("Generated property ${names.joinToString("/")}[$index] is not a String")
    }
}

private fun readSourceString(target: Any, vararg names: String): String =
    readSourceRequired(target, *names) as String
